"""Shared browser acceptance flow for a disposable campaign with Guard and Hero."""
from playwright.sync_api import expect


def runtime_flow(page, origin, campaign_id, artifacts):
    page.goto(f'{origin}/campaigns/?lang=en&campaign={campaign_id}')
    panel = page.get_by_role('region', name='Run campaign')
    tabs = page.get_by_role('navigation', name='Campaign views')
    dialog = page.get_by_role('dialog')
    expect(tabs.get_by_role('button', name='Run session', exact=True)).to_have_attribute('aria-current', 'page')
    expect(page.locator('.wiki-sidebar')).to_be_hidden()
    panel.get_by_role('button', name='World state and stats', exact=True).click()
    dialog.get_by_label('Stat / resource name', exact=True).select_option('__create__')
    dialog.get_by_label('New name', exact=True).fill('gold')
    dialog.get_by_label('Value', exact=True).fill('12')
    dialog.get_by_role('button', name='Set value', exact=True).click()
    expect(dialog.locator('.runtime-values')).to_contain_text('12')
    dialog.get_by_role('button', name='Close / Zamknij').click()
    tabs.get_by_role('button', name='Characters', exact=True).click()
    page.locator('.session-character').filter(has_text='Guard').click()
    dialog.get_by_label('Stat', exact=True).select_option('__create__')
    dialog.get_by_label('New name', exact=True).fill('health')
    dialog.get_by_label('Value', exact=True).fill('10')
    dialog.get_by_role('button', name='Save stat', exact=True).click()
    expect(dialog.locator('.runtime-values')).to_contain_text('10')
    expect(dialog).to_contain_text('No description yet.')
    dialog.get_by_role('button', name='Close / Zamknij').click()
    tabs.get_by_role('button', name='Run session', exact=True).click()
    panel.get_by_role('button', name='Plan an event', exact=True).first.click()
    dialog.get_by_label('What will happen?', exact=True).fill('The gate closes')
    dialog.get_by_label('Situation and stakes', exact=True).fill('Without help, the guard closes the gate.')
    dialog.get_by_label('From day', exact=True).fill('2')
    dialog.get_by_label('Through day (inclusive)', exact=True).fill('3')
    dialog.locator('.event-requirements > summary').click()
    dialog.get_by_label('Guard', exact=True).check()
    dialog.get_by_role('button', name='Add stat condition', exact=True).click()
    dialog.get_by_label('Condition', exact=True).select_option('actors')
    dialog.get_by_label('Condition character', exact=True).select_option(label='Guard')
    dialog.get_by_label('Value name', exact=True).select_option('health')
    dialog.get_by_label('Threshold', exact=True).fill('0')
    dialog.get_by_label('What was decided / what happened?', exact=True).fill('Pay the guard')
    dialog.get_by_role('button', name='Add consequence', exact=True).click()
    dialog.get_by_label('Consequence', exact=True).select_option('ModifyResource')
    dialog.get_by_label('Fact / stat / relationship name', exact=True).select_option('gold')
    dialog.get_by_label('Change (+ / −)', exact=True).fill('-5')
    dialog.get_by_role('button', name='Add consequence', exact=True).click()
    dialog.get_by_label('Fact / stat / relationship name', exact=True).nth(1).select_option('__create__')
    dialog.get_by_label('New name', exact=True).fill('safe')
    dialog.get_by_role('button', name='Save event', exact=True).click()
    expect(dialog).to_have_count(0)
    event = panel.locator('.runtime-event').filter(has_text='The gate closes')
    expect(event).to_contain_text('From day 2')
    event.locator('summary').click()
    expect(event.get_by_role('button', name='Review consequences: Pay the guard')).to_be_disabled()
    # Add downstream event and today's deadline via API to exercise availability preview.
    def command(data):
        return page.evaluate('''async ({id,data})=>{
            const session=await (await fetch('/api/session/')).json();
            const url='/api/campaigns/'+id+'/runtime/';
            const before=await (await fetch(url)).json();
            const response=await fetch(url,{method:'POST',headers:{'Content-Type':'application/json','X-CSRFToken':session.csrf},body:JSON.stringify({...data,version:before.version})});
            if(!response.ok)throw Error(await response.text());return await response.json();
        }''', {'id':campaign_id,'data':data})
    for event_id, title, start, end, flags in [('welcome','Welcome inside',2,4,['safe']),('deadline','A last chance',1,1,[])]:
        command({'action':'add_event','event':{'id':event_id,'title':title,'MinTimeUnit':start,'MaxTimeUnit':end,'requiredFlags':flags,'choices':[{'text':'Continue','outcomes':[]}]}})
    page.reload()
    panel.get_by_role('button', name='Next day', exact=True).click()
    expect(dialog).to_contain_text('A last chance · Expired')
    expect(dialog).to_contain_text('The gate closes · Available now')
    dialog.get_by_role('button', name='Back', exact=True).click()
    expect(panel.get_by_role('heading', name='Day 1', exact=True)).to_be_visible()
    panel.get_by_role('button', name='Next day', exact=True).click()
    dialog.get_by_role('button', name='Confirm and save', exact=True).click()
    expect(panel.get_by_role('heading', name='Day 2', exact=True)).to_be_visible()
    panel.get_by_role('button', name='Dismiss result').click()
    event.get_by_role('button', name='Guard', exact=True).click()
    expect(dialog.locator('.runtime-values')).to_contain_text('health10')
    expect(dialog).to_contain_text('The gate closes')
    page.screenshot(path=str(artifacts/'character.png'))
    page.keyboard.press('Escape')
    page.screenshot(path=str(artifacts/'desktop.png'),full_page=True)
    page.set_viewport_size({'width':390,'height':844})
    page.screenshot(path=str(artifacts/'mobile.png'),full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'horizontal overflow'
    assert event.get_by_role('button',name='Review consequences: Pay the guard').bounding_box()['y'] < 844
    event.get_by_role('button', name='Review consequences: Pay the guard').click()
    expect(dialog).to_contain_text('12 → 7')
    expect(dialog).to_contain_text('Welcome inside · Available now')
    page.screenshot(path=str(artifacts/'decision-mobile.png'))
    # Preview and cancel leave the actual runtime untouched.
    state=page.evaluate('async id=>await (await fetch("/api/campaigns/"+id+"/runtime/")).json()',campaign_id)
    assert state['resources']['gold']==12
    dialog.get_by_role('button', name='Back', exact=True).click()
    event.get_by_role('button', name='Review consequences: Pay the guard').click()
    dialog.get_by_role('button', name='Confirm and save', exact=True).click()
    expect(dialog).to_have_count(0)
    expect(panel.locator('.runtime-receipt')).to_contain_text('12 → 7')
    expect(panel.locator('.runtime-event').filter(has_text='Welcome inside')).to_contain_text('Available now')
    page.reload()
    expect(panel.locator('.session-context .runtime-values')).to_contain_text('gold7')
    panel.locator('.runtime-history > summary').click()
    expect(panel.locator('.runtime-history')).to_contain_text('The gate closes: Pay the guard')
    tabs.get_by_role('button', name='Timeline', exact=True).click()
    panel.get_by_label('Show', exact=True).select_option('archive')
    expect(panel.locator('.session-timeline')).to_contain_text('The gate closes')
    tabs.get_by_role('button', name='Characters', exact=True).click()
    expect(panel.locator('.session-character').filter(has_text='Guard')).to_be_visible()
    panel.locator('.session-character').filter(has_text='Guard').click()
    dialog.get_by_role('button', name='Edit description and publication').click()
    expect(page.locator('.wiki-article-title')).to_contain_text('Guard')
    assert 'page=' in page.url
    page.reload()
    expect(page.locator('.wiki-article-title')).to_contain_text('Guard')
    expect(tabs.get_by_role('button', name='World material')).to_have_attribute('aria-current','page')
    tabs.get_by_role('button', name='Run session', exact=True).click()
    expect(page.locator('.wiki-article-title')).to_be_hidden()
    print('PASS: four views, character sheet/stats, event preparation, real preview/cancel/save, deadlines, downstream unlock, persistence, history, deep links and mobile layout')
